def _panel_title(ax, letter: str, title: str):
    """Add a left-anchored panel heading with a fixed title-to-axes offset."""
    heading = ax.set_title(f"({letter})  {title}", loc="left", pad=10)
    heading.set_x(0)
    heading.set_ha("left")
    return heading


def fig2(df: pd.DataFrame):
    """Compose a data-driven, three-panel anatomy of observed news attention."""
    plt = C.use_style()
    import matplotlib.dates as mdates
    import matplotlib.ticker as mticker

    fig = plt.figure(figsize=(7.15, 6.15), constrained_layout=True, facecolor="white")
    # A direct shared GridSpec, rather than a nested top-left grid, locks the
    # rendered widths of Panels A and C to the same column geometry.
    grid = fig.add_gridspec(4, 2, height_ratios=[2.1, 1.0, 0.22, 3.15],
                           width_ratios=[1.24, 1.0], wspace=0.08, hspace=0.08)
    axa_volume = fig.add_subplot(grid[0, 0])
    axa_intensity = fig.add_subplot(grid[1, 0], sharex=axa_volume)
    axb = fig.add_subplot(grid[:2, 1])
    axc = fig.add_subplot(grid[3, 0])
    axd = fig.add_subplot(grid[3, 1])

    # (a) Volume and coverage intensity use separate, aligned axes to avoid dual-scale distortion.
    monthly = (df.dropna(subset=["event_date"]).assign(
        ym=lambda x: x.event_date.dt.to_period("M").dt.to_timestamp()
    ).groupby("ym").agg(events=("event_id", "size"), articles=("n_articles", "sum"))
     .reset_index())
    monthly["articles_per_event"] = monthly.articles / monthly.events
    monthly["events_smooth"] = monthly.events.rolling(12, center=True, min_periods=6).mean()
    monthly["intensity_smooth"] = monthly.articles_per_event.rolling(
        12, center=True, min_periods=6
    ).mean()

    axa_volume.bar(monthly.ym, monthly.events, width=24, color="#D3E5F1",
                   edgecolor="none", zorder=1)
    axa_volume.plot(monthly.ym, monthly.events_smooth, color=PED, linewidth=1.55,
                    zorder=3)
    axa_volume.axvspan(pd.Timestamp("2020-03-01"), pd.Timestamp("2021-06-30"),
                       color="#F1F3F4", zorder=0)
    axa_volume.text(pd.Timestamp("2020-10-01"), axa_volume.get_ylim()[1] * 0.95,
                    "2020-2021", ha="center", va="top", fontsize=6.0, color=NEUTRAL)
    axa_volume.set_ylabel("Events per month")
    _panel_title(axa_volume, "a", "Temporal Profile of Observed Coverage")
    axa_volume.tick_params(labelbottom=False)
    axa_volume.set_ylim(bottom=0)

    overall_mean = df.n_articles.mean()
    axa_intensity.plot(monthly.ym, monthly.articles_per_event, color="#C7D3DB",
                        linewidth=0.65, zorder=1)
    axa_intensity.plot(monthly.ym, monthly.intensity_smooth, color=HIGHLIGHT,
                        linewidth=1.45, zorder=3)
    axa_intensity.axhline(overall_mean, color=INK, linewidth=0.65,
                           linestyle=(0, (2, 2)), zorder=2)
    axa_intensity.annotate(f"Overall mean = {overall_mean:.2f}",
                           xy=(monthly.ym.iloc[-2], overall_mean), xytext=(-2, 3),
                           textcoords="offset points", ha="right", va="bottom",
                           fontsize=5.9, color=INK)
    axa_intensity.set_ylabel("Articles per event")
    axa_intensity.set_xlabel("Event date")
    axa_intensity.xaxis.set_major_locator(mdates.YearLocator(2))
    axa_intensity.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))
    axa_intensity.set_ylim(bottom=max(0, monthly.articles_per_event.min() * 0.78))
    fig.align_ylabels([axa_volume, axa_intensity])
    axa_volume.yaxis.set_label_coords(-0.115, 0.5)
    axa_intensity.yaxis.set_label_coords(-0.115, 0.5)

    # (b) The mirrored composition encodes the difference between events and all linked attention.
    tier = (df.groupby("cov_tier", observed=True).agg(
        events=("event_id", "size"), articles=("n_articles", "sum")
    ).reindex(TIERS))
    tier["event_share"] = tier.events / tier.events.sum()
    tier["article_share"] = tier.articles / tier.articles.sum()
    y = np.arange(len(TIERS))[::-1]
    axb.barh(y, -tier.event_share.to_numpy(), height=0.56, color=PED,
             edgecolor="white", linewidth=0.55, alpha=0.92)
    axb.barh(y, tier.article_share.to_numpy(), height=0.56, color=HIGHLIGHT,
             edgecolor="white", linewidth=0.55, alpha=0.92)
    axb.axvline(0, color=INK, linewidth=0.7, zorder=0)
    for yi, (_, row) in zip(y, tier.iterrows()):
        if row.event_share >= 0.10:
            event_x, event_ha, event_color = -row.event_share / 2, "center", "white"
        else:
            event_x, event_ha, event_color = -row.event_share - 0.022, "right", INK
        if row.article_share >= 0.10:
            article_x, article_ha, article_color = row.article_share / 2, "center", "white"
        else:
            article_x, article_ha, article_color = row.article_share + 0.022, "left", INK
        axb.text(event_x, yi, f"{row.event_share:.1%}", ha=event_ha, va="center",
                 fontsize=6.2, fontweight="bold", color=event_color)
        axb.text(article_x, yi, f"{row.article_share:.1%}", ha=article_ha, va="center",
                 fontsize=6.2, fontweight="bold", color=article_color)
    axb.text(0.25, 0.925, "Share of events", transform=axb.transAxes,
             ha="center", va="bottom", fontsize=7.1, fontweight="bold", color=PED)
    axb.text(0.75, 0.925, "Share of linked articles", transform=axb.transAxes,
             ha="center", va="bottom", fontsize=7.1, fontweight="bold", color=HIGHLIGHT)
    axb.set_yticks(y)
    axb.set_yticklabels([TIER_DISPLAY[t] for t in TIERS])
    axb.set_xlabel("Share of corpus (%)")
    axb.set_ylabel("Coverage tier")
    axb.set_xlim(-0.87, 0.87)
    axb.set_ylim(-0.65, 3.9)
    axb.xaxis.set_major_locator(mticker.FixedLocator([-0.8, -0.4, 0, 0.4, 0.8]))
    axb.xaxis.set_major_formatter(mticker.FuncFormatter(lambda x, _: f"{abs(x) * 100:.0f}"))
    axb.grid(False)
    # Keep the column's y-axis reference line visible so Panels B and D share
    # one exact left-hand visual anchor.
    axb.spines["left"].set_visible(True)
    axb.spines["left"].set_color(INK)
    axb.spines["left"].set_linewidth(0.8)
    axb.spines["bottom"].set_color("#BFC7CC")
    axb.tick_params(axis="y", length=0)
    _panel_title(axb, "b", "Coverage Allocation by Intensity Tier")

    # (c-d) The phase-space field and survival curves make the intensity-persistence relationship explicit.
    _attention_phase_space(axc, df)
    _persistence_survival(axd, df)
    fig.align_ylabels([axb, axd])
    _panel_title(axc, "c", "Attention Phase Space")
    _panel_title(axd, "d", "Persistence Survival by Coverage Intensity")

    fig.savefig(C.FIGURES / "fig2.pdf", facecolor="white")
    fig.savefig(C.FIGURES / "fig2.png", dpi=600, facecolor="white")
    plt.close(fig)
    print(f"[fig2] wrote {C.FIGURES/'fig2.pdf'}")


