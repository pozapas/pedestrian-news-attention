def fmt_pct(x): return f"{100*x:.0f}\\%"
def fmt_med(x): return f"{x:.0f}" if not np.isnan(x) else "--"


def shaded_cell(val_str, t, dark_text_thresh=0.62):
    """Return a \\cellcolor-shaded cell; white text when the fill is dark."""
    hexc = palette.ramp_hex(t).lstrip("#")
    if t >= dark_text_thresh:
        return f"\\cellcolor[HTML]{{{hexc}}}\\textcolor{{white}}{{{val_str}}}"
    return f"\\cellcolor[HTML]{{{hexc}}}{val_str}"


def row_norm(vals):
    """Min-max normalise a row of numeric values to [0,1] for the ramp."""
    v = np.array(vals, dtype=float)
    finite = v[np.isfinite(v)]
    if finite.size == 0:
        return np.zeros_like(v)
    lo, hi = finite.min(), finite.max()
    if hi - lo < 1e-12:
        return np.full_like(v, 0.5)
    out = (v - lo) / (hi - lo)
    out[~np.isfinite(out)] = 0.0
    return out


def build_table1(df: pd.DataFrame) -> dict:
    groups = {t: df[df.cov_tier == t] for t in TIERS}
    groups["All"] = df
    cols = TIERS + ["All"]
    total = len(df)

    # metric rows: (label, func mapping subframe->value, formatter, is_pct)
    def med_age(g):
        a = g.age_youngest.dropna()
        return a.median() if len(a) else np.nan
    rows = [
        ("Events, $n$",              lambda g: len(g),                    "N"),
        ("Median articles",          lambda g: g.n_articles.median(),     "med"),
        ("Median outlets",           lambda g: g.n_outlets.median(),      "med"),
        ("Victim named",             lambda g: g.victim_named.mean(),     "pct"),
        ("Median victim age, yr",    med_age,                             "med"),
        ("Child ($\\le$12)",         lambda g: g.child.mean(),            "pct"),
        ("Age $\\ge$65",             lambda g: g.elderly.mean(),          "pct"),
        ("Female",                   lambda g: g.female.mean(),           "pct"),
        ("Hit-and-run",              lambda g: g.hit_run_flag.mean(),     "pct"),
        ("Charges reported",         lambda g: g.charges_reported.mean(), "pct"),
        ("Dark conditions",          lambda g: g.dark.mean(),             "pct"),
        ("Multi-fatality",           lambda g: g.multi_fatality.mean(),   "pct"),
    ]

    lines = []
    lines.append("% Auto-generated by p02_descriptives.py -- do not edit by hand.")
    lines.append("\\begin{tabular}{l cccc c}")
    lines.append("\\toprule")
    hdr = " & ".join(["Coverage tier"] + [TIER_LABEL[t] for t in TIERS] + ["All"]) + " \\\\"
    lines.append(hdr)
    # subheader: N and % per tier
    subvals = []
    for t in TIERS:
        n = len(groups[t]); subvals.append(f"{n:,}")
    lines.append("\\midrule")

    payload_rows = {}
    for label, func, kind in rows:
        vals = [func(groups[c]) for c in cols]
        payload_rows[label] = {c: (None if (isinstance(v, float) and np.isnan(v)) else float(v))
                               for c, v in zip(cols, vals)}
        if kind == "N":
            # data bars, bar proportion = n / total
            cells = []
            for c in cols:
                n = len(groups[c])
                pct = 100 * n / total
                lab = f"{n:,}" if c != "All" else f"\\textbf{{{n:,}}}"
                cells.append(f"\\databarL{{{n}}}{{{total}}}{{{lab}}}")
            lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
            lines.append("\\addlinespace[1pt]")
            continue
        # heat-shaded numeric cells; normalise across the 4 tier columns only
        tvals = [func(groups[t]) for t in TIERS]
        norms = row_norm(tvals)
        # extend normalisation to All using same lo/hi
        allv = func(groups["All"])
        finite = np.array([v for v in tvals if np.isfinite(v)], float)
        lo, hi = (finite.min(), finite.max()) if finite.size else (0, 1)
        all_t = 0.5 if hi - lo < 1e-12 else np.clip((allv - lo) / (hi - lo), 0, 1)
        fmt = (lambda x: fmt_pct(x)) if kind == "pct" else (lambda x: fmt_med(x))
        cells = []
        for t, tv, nt in zip(TIERS, tvals, norms):
            cells.append(shaded_cell(fmt(tv), nt))
        cells.append(shaded_cell(fmt(allv), float(all_t)))
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    (C.TABLES / "table1.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[table1] wrote {C.TABLES/'table1.tex'}")
    return payload_rows


