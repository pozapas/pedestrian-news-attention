TIER_COLORS = ["#BFD7EA", "#82B6D7", "#3F8FC1", PED]
TIER_DISPLAY = {
    "1": "1 article", "2-3": "2-3 articles", "4-9": "4-9 articles", "10+": "≥10 articles",
}
DURATION_LABELS = ["Same day", "1 day", "2-7 days", "8-30 days", ">30 days"]


def _flow_patch(x0, x1, y0, y1, height, color):
    """Create one smooth, area-preserving alluvial ribbon."""
    from matplotlib.path import Path
    from matplotlib.patches import PathPatch

    bend = (x1 - x0) * 0.38
    vertices = [
        (x0, y0),
        (x0 + bend, y0), (x1 - bend, y1), (x1, y1),
        (x1, y1 + height),
        (x1 - bend, y1 + height), (x0 + bend, y0 + height), (x0, y0 + height),
        (x0, y0),
    ]
    codes = [Path.MOVETO, Path.CURVE4, Path.CURVE4, Path.CURVE4,
             Path.LINETO, Path.CURVE4, Path.CURVE4, Path.CURVE4, Path.CLOSEPOLY]
    return PathPatch(Path(vertices, codes), facecolor=color, edgecolor="white",
                     linewidth=0.24, alpha=0.82, zorder=1)


def _attention_pathways(ax, df: pd.DataFrame):
    """Draw the event-preserving flow from intensity tier to persistence tier."""
    from matplotlib.patches import Rectangle

    d = df.copy()
    d["duration_bin"] = pd.cut(
        d.span_days.fillna(0).clip(lower=0),
        bins=[-1, 0, 1, 7, 30, np.inf], labels=DURATION_LABELS,
    )
    flows = pd.crosstab(d.cov_tier, d.duration_bin).reindex(
        index=TIERS, columns=DURATION_LABELS, fill_value=0,
    )
    source_totals = flows.sum(axis=1)
    target_totals = flows.sum(axis=0)
    n_total = int(flows.to_numpy().sum())

    gap = 0.034
    scale = (1 - gap * (len(TIERS) - 1)) / n_total

    def stack_bounds(totals):
        y = 0.0
        bounds = {}
        for key, value in totals.items():
            height = float(value) * scale
            bounds[key] = (y, y + height)
            y += height + gap
        return bounds

    source_bounds = stack_bounds(source_totals)
    target_bounds = stack_bounds(target_totals)
    source_cursor = {key: source_bounds[key][0] for key in TIERS}
    target_cursor = {key: target_bounds[key][0] for key in DURATION_LABELS}

    for tier, color in zip(TIERS, TIER_COLORS):
        for duration in DURATION_LABELS:
            count = int(flows.loc[tier, duration])
            if not count:
                continue
            height = count * scale
            ax.add_patch(_flow_patch(0.14, 0.84, source_cursor[tier],
                                     target_cursor[duration], height, color))
            source_cursor[tier] += height
            target_cursor[duration] += height

    # Source and destination strata make every ribbon width directly auditable.
    for tier, color in zip(TIERS, TIER_COLORS):
        lo, hi = source_bounds[tier]
        ax.add_patch(Rectangle((0.105, lo), 0.035, hi - lo, facecolor=color,
                               edgecolor="white", linewidth=0.7, zorder=2))

    for tier in ["1", "2-3"]:
        lo, hi = source_bounds[tier]
        count = int(source_totals.loc[tier])
        ax.text(0.088, (lo + hi) / 2, f"{TIER_DISPLAY[tier]}\n{count:,} ({count / n_total:.1%})",
                ha="right", va="center", fontsize=6.0, color=INK, linespacing=1.12)

    source_label_y = {"10+": 0.992, "4-9": 0.922}
    for tier, y_text in source_label_y.items():
        lo, hi = source_bounds[tier]
        count = int(source_totals.loc[tier])
        ax.plot([0.105, 0.092], [(lo + hi) / 2, y_text], color="#AEBCC6",
                linewidth=0.45, clip_on=False, zorder=2)
        ax.text(0.087, y_text, f"{TIER_DISPLAY[tier]}: {count:,} ({count / n_total:.1%})",
                ha="right", va="center", fontsize=5.8, color=INK)

    for duration in DURATION_LABELS:
        lo, hi = target_bounds[duration]
        ax.add_patch(Rectangle((0.84, lo), 0.035, hi - lo, facecolor="#E9EFF3",
                               edgecolor="white", linewidth=0.7, zorder=2))

    # The four rare persistence strata are deliberately fanned into a label gutter,
    # avoiding unreadable collisions while retaining one-to-one leader lines.
    label_y = {">30 days": 0.985, "8-30 days": 0.915, "2-7 days": 0.845, "1 day": 0.775}
    for duration, y_text in label_y.items():
        lo, hi = target_bounds[duration]
        count = int(target_totals.loc[duration])
        ax.plot([0.875, 0.91], [(lo + hi) / 2, y_text], color="#AEBCC6",
                linewidth=0.45, clip_on=False, zorder=2)
        ax.text(0.918, y_text, f"{duration}: {count:,} ({count / n_total:.1%})",
                ha="left", va="center", fontsize=5.8, color=INK)

    lo, hi = target_bounds["Same day"]
    count = int(target_totals.loc["Same day"])
    ax.text(0.918, (lo + hi) / 2, f"Same day\n{count:,} ({count / n_total:.1%})",
            ha="left", va="center", fontsize=6.0, color=INK, linespacing=1.12)

    ax.set_xlim(0, 1.25)
    ax.set_ylim(-0.015, 1.075)
    ax.set_axis_off()


def _attention_persistence_matrix(ax, df: pd.DataFrame):
    """Show the conditional lifespan profile associated with each coverage tier."""
    from matplotlib.patches import FancyBboxPatch

    d = df.copy()
    d["duration_bin"] = pd.cut(
        d.span_days.fillna(0).clip(lower=0),
        bins=[-1, 0, 1, 7, 30, np.inf], labels=DURATION_LABELS,
    )
    counts = pd.crosstab(d.cov_tier, d.duration_bin).reindex(
        index=TIERS, columns=DURATION_LABELS, fill_value=0,
    )
    row_total = counts.sum(axis=1)
    conditional = counts.div(row_total, axis=0)
    follow_up = 1 - conditional["Same day"]
    n_total = int(row_total.sum())

    matrix_left, cell_width, cell_gap = 0.285, 0.112, 0.013
    cell_height = 0.142
    y_positions = [0.655, 0.468, 0.281, 0.094]
    follow_x, follow_width = 0.925, 0.205
    cmap = palette.seq_cmap()

    ax.text(matrix_left, 0.902, "Coverage lifespan after first article", ha="left",
            va="bottom", fontsize=6.6, fontweight="bold", color=INK)
    for col, duration in enumerate(DURATION_LABELS):
        x = matrix_left + col * (cell_width + cell_gap)
        ax.text(x + cell_width / 2, 0.853, duration, ha="center", va="bottom",
                fontsize=6.0, fontweight="bold", color=INK)
    ax.text(follow_x + follow_width / 2, 0.853, "Follow-up\n(≥1 day)", ha="center",
            va="bottom", fontsize=6.0, fontweight="bold", color=HIGHLIGHT,
            linespacing=1.0)

    for tier, y in zip(TIERS, y_positions):
        total = int(row_total.loc[tier])
        ax.text(matrix_left - 0.027, y + cell_height / 2,
                f"{TIER_DISPLAY[tier]}\n{total:,} events ({total / n_total:.1%})",
                ha="right", va="center", fontsize=6.0, color=INK, linespacing=1.1)

        for col, duration in enumerate(DURATION_LABELS):
            x = matrix_left + col * (cell_width + cell_gap)
            count = int(counts.loc[tier, duration])
            share = float(conditional.loc[tier, duration])
            shade = 0.04 + 0.96 * np.sqrt(share)
            color = cmap(shade)
            card = FancyBboxPatch(
                (x, y), cell_width, cell_height,
                boxstyle="round,pad=0.004,rounding_size=0.014",
                facecolor=color, edgecolor="white", linewidth=0.8,
            )
            ax.add_patch(card)
            text_color = "white" if share >= 0.54 else INK
            label = f"{count:,}\n{share:.0%}" if count else "0\n0%"
            ax.text(x + cell_width / 2, y + cell_height / 2, label,
                    ha="center", va="center", fontsize=6.0, fontweight="bold",
                    color=text_color, linespacing=1.05)

        follow = float(follow_up.loc[tier])
        track = FancyBboxPatch(
            (follow_x, y), follow_width, cell_height,
            boxstyle="round,pad=0.004,rounding_size=0.014",
            facecolor="#F1F3F4", edgecolor="white", linewidth=0.8,
        )
        ax.add_patch(track)
        if follow > 0:
            fill = FancyBboxPatch(
                (follow_x, y), follow_width * follow, cell_height,
                boxstyle="round,pad=0.004,rounding_size=0.014",
                facecolor=HIGHLIGHT, edgecolor="none", linewidth=0,
            )
            ax.add_patch(fill)
        follow_color = "white" if follow >= 0.43 else INK
        ax.text(follow_x + follow_width / 2, y + cell_height / 2, f"{follow:.0%}",
                ha="center", va="center", fontsize=6.2, fontweight="bold", color=follow_color)

    ax.text(matrix_left, 0.035,
            "Cells show event count and within-tier share; color intensity encodes conditional persistence.",
            ha="left", va="bottom", fontsize=5.6, color=NEUTRAL)
    ax.set_xlim(0, 1.18)
    ax.set_ylim(0, 1.0)
    ax.set_axis_off()


def _attention_phase_space(ax, df: pd.DataFrame):
    """Render a smoothed phase-space density for coverage intensity and lifespan."""
    import matplotlib.ticker as mticker

    span = df.span_days.fillna(0).clip(lower=0).to_numpy(float)
    articles = df.n_articles.to_numpy(float)
    x = np.log1p(span)
    y = np.log10(articles)
    x_edges = np.linspace(0, np.log1p(span.max() + 1), 40)
    y_edges = np.linspace(0, np.log10(articles.max()), 34)
    density, _, _ = np.histogram2d(x, y, bins=(x_edges, y_edges))

    # A small binomial blur creates a smooth density field without adding a new dependency.
    kernel = np.array([1, 4, 6, 4, 1], dtype=float) / 16
    for _ in range(2):
        density = np.apply_along_axis(lambda v: np.convolve(v, kernel, mode="same"), 0, density)
        density = np.apply_along_axis(lambda v: np.convolve(v, kernel, mode="same"), 1, density)
    field = np.log1p(density)
    field /= field.max()
    x_mid = (x_edges[:-1] + x_edges[1:]) / 2
    y_mid = (y_edges[:-1] + y_edges[1:]) / 2

    ax.contourf(x_mid, y_mid, field.T,
                levels=[0.035, 0.08, 0.15, 0.28, 0.45, 0.65, 1.0],
                cmap=palette.seq_cmap(), antialiased=True, zorder=1)
    ax.contour(x_mid, y_mid, field.T, levels=[0.08, 0.20, 0.40, 0.65],
               colors="white", linewidths=0.55, alpha=0.9, zorder=2)

    medians = (df.groupby("cov_tier", observed=True).agg(
        lifespan=("span_days", "median"), articles=("n_articles", "median")
    ).reindex(TIERS))
    ax.plot(np.log1p(medians.lifespan), np.log10(medians.articles), color=INK,
            linewidth=1.0, marker="o", markersize=3.4, zorder=4)
    endpoint = medians.loc["10+"]
    ax.annotate("Tier medians", (np.log1p(endpoint.lifespan), np.log10(endpoint.articles)),
                xytext=(5, 4), textcoords="offset points", fontsize=5.3,
                color=INK, zorder=5)

    # Spearman correlation without requiring SciPy: Pearson correlation of average ranks.
    rho = np.corrcoef(pd.Series(span).rank().to_numpy(),
                      pd.Series(articles).rank().to_numpy())[0, 1]
    single_story = ((span == 0) & (articles == 1)).mean()
    persistent = (span >= 8).mean()
    ax.text(0.98, 0.96, f"Spearman ρ = {rho:.2f}", transform=ax.transAxes,
            ha="right", va="top", fontsize=5.9, color=INK)
    ax.text(0.055, 0.80, f"Same-day, one story\n{single_story:.0%} of events",
            transform=ax.transAxes, ha="left", va="top", fontsize=5.6, color=INK,
            bbox=dict(facecolor="white", edgecolor="none", alpha=0.82, pad=1.1), zorder=5)
    ax.annotate(f"Persistent tail (≥8 days)\n{persistent:.1%} of events",
                xy=(np.log1p(12), np.log10(4)), xytext=(2.7, 1.72), textcoords="data",
                arrowprops=dict(arrowstyle="-", color=INK, linewidth=0.55),
                fontsize=5.5, color=INK, zorder=5)

    day_ticks = np.array([0, 1, 7, 30, 180, 475])
    article_ticks = np.array([1, 2, 5, 10, 50, 226])
    ax.xaxis.set_major_locator(mticker.FixedLocator(np.log1p(day_ticks)))
    ax.xaxis.set_major_formatter(mticker.FixedFormatter([str(v) for v in day_ticks]))
    ax.yaxis.set_major_locator(mticker.FixedLocator(np.log10(article_ticks)))
    ax.yaxis.set_major_formatter(mticker.FixedFormatter([str(v) for v in article_ticks]))
    ax.set_xlim(0, np.log1p(475))
    ax.set_ylim(0, np.log10(226))
    ax.set_xlabel("Coverage lifespan (days)")
    ax.set_ylabel("Articles per event")
    ax.grid(False)


def _persistence_survival(ax, df: pd.DataFrame):
    """Plot event-level persistence survival functions stratified by coverage intensity."""
    import matplotlib.ticker as mticker

    time = np.r_[0, np.arange(1, 31), [45, 60, 90, 180, 365, 475]]
